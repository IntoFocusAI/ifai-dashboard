#!/usr/bin/env python3
"""Build docs/fdd/register.md: one line per FDD row (ID, status, milestone, file).

Usage:
  python3 scripts/fdd-register.py          # rewrite docs/fdd/register.md
  python3 scripts/fdd-register.py --check  # exit 1 if register.md is stale or a row ID repeats
  python3 scripts/fdd-register.py --open   # print rows that are not CURRENT or LATER

A row starts with a line like:  **X-01 CURRENT** · Launch
Change a row's status by editing that line in its view file, then run this
script and commit both files together.
"""
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FDD = ROOT / "docs" / "fdd"
ROW = re.compile(r"^\*\*([A-Z]{1,2}-\d+) (CURRENT|REFINE|TARGET|DECISION|LATER)\*\*\s*·\s*(.+?)\s*$")
ORDER = ["cross-dashboard.md", "summary.md", "catalog-health.md", "ai-search.md",
         "ai-readiness.md", "competitive-radar.md", "action-items.md", "roadmap.md",
         "minimal.md", "launch-and-registers.md"]


def rows():
    for name in ORDER:
        path = FDD / name
        if not path.exists():
            continue
        for line in path.read_text().splitlines():
            m = ROW.match(line)
            if m:
                yield m.group(1), m.group(2), m.group(3), name


def render(all_rows):
    counts = Counter(r[1] for r in all_rows)
    summary = ", ".join(f"{counts[s]} {s}" for s in ["CURRENT", "REFINE", "TARGET", "DECISION", "LATER"])
    out = [
        "# FDD row register",
        "",
        "Generated by `python3 scripts/fdd-register.py` from the view files. Do not edit by hand.",
        "",
        f"{len(all_rows)} rows: {summary}.",
        "",
        "| ID | Status | Milestone | File |",
        "|---|---|---|---|",
    ]
    out += [f"| {i} | {s} | {m} | [{f}]({f}) |" for i, s, m, f in all_rows]
    return "\n".join(out) + "\n"


def main():
    all_rows = list(rows())
    dupes = [i for i, n in Counter(r[0] for r in all_rows).items() if n > 1]
    if dupes:
        print("Repeated row IDs:", ", ".join(dupes))
        sys.exit(1)
    text = render(all_rows)
    target = FDD / "register.md"
    if "--open" in sys.argv:
        for i, s, m, f in all_rows:
            if s not in ("CURRENT", "LATER"):
                print(f"{i}\t{s}\t{m}\t{f}")
        return
    if "--check" in sys.argv:
        if not target.exists() or target.read_text() != text:
            print("docs/fdd/register.md is stale. Run: python3 scripts/fdd-register.py")
            sys.exit(1)
        print(f"register OK ({len(all_rows)} rows)")
        return
    target.write_text(text)
    print(f"wrote {target.relative_to(ROOT)} ({len(all_rows)} rows)")


if __name__ == "__main__":
    main()
