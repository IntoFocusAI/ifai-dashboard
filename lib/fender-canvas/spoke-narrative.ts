import type { ReactNode } from "react";
import narrative from "@/data/canvas-narrative.json";
import type { SpokeDefinition, SpokeId } from "@/components/v3/spoke-data-types";
import { activeClientSettings } from "@/lib/client/active-client";
import { bindCopy } from "@/lib/fender-canvas/template-vars";

type NarrativeSpoke = {
  badge: string;
  title: string;
  desc: string;
  tabs: string[];
  navLabel: string;
  next: SpokeId;
  tabTemplates: string[];
};

type NarrativeSpec = { spokes: Record<SpokeId, NarrativeSpoke> };

/** Fills the brand tokens from the client's settings: {brand}, {lead_brand}, {brand_site}. */
export function bindBrandTokens(text: string): string {
  const s = activeClientSettings();
  return text
    .replace(/\{lead_brand\}/g, s.lead_brand_label)
    .replace(/\{brand_site\}/g, s.brand_site_label)
    .replace(/\{brand\}/g, s.display_name);
}

/**
 * Narrative copy for the brand on screen: one brand-free template for every client (H-09,
 * decision 105), filled from its settings. Briefing, Opportunity and Revenue Estimates are
 * generated by components from the client's data, so their templates are empty.
 */
export function clientNarrative(): NarrativeSpec {
  const base = narrative as unknown as NarrativeSpec;
  const spokes = {} as Record<SpokeId, NarrativeSpoke>;
  for (const id of Object.keys(base.spokes) as SpokeId[]) {
    const row = base.spokes[id];
    spokes[id] = {
      ...row,
      badge: bindBrandTokens(row.badge),
      title: bindBrandTokens(row.title),
      desc: bindBrandTokens(row.desc),
      tabTemplates: row.tabTemplates.map(bindBrandTokens),
    };
  }
  return { spokes };
}

/** Static narrative config (templates use `{metric_id}` placeholders filled at render). */
export function buildNarrativeSpokes(): Record<SpokeId, SpokeDefinition> {
  const out = {} as Record<SpokeId, SpokeDefinition>;
  const spokes = clientNarrative().spokes;

  for (const id of Object.keys(spokes) as SpokeId[]) {
    const row = spokes[id];
    out[id] = {
      badge: row.badge,
      title: row.title,
      desc: row.desc,
      tabs: row.tabs,
      navLabel: row.navLabel,
      next: row.next,
      render: (tabIdx: number): ReactNode | string => row.tabTemplates[tabIdx] ?? "",
    };
  }
  return out;
}

export function bindNarrativeSpoke(
  spoke: SpokeDefinition,
  vars: Record<string, string>,
): SpokeDefinition {
  return {
    ...spoke,
    desc: bindCopy(spoke.desc, vars),
    tabs: spoke.tabs.map((t) => bindCopy(t, vars)),
    render: (tabIdx) => {
      const template = spoke.render(tabIdx);
      if (typeof template !== "string") return template;
      return bindCopy(template, vars);
    },
  };
}
